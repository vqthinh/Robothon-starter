def run(ablation=False, verbose=True):
    if verbose:
        print("  [1/4] task suite (closed-loop force control)...")
    rows = run_trials()
    abl = None
    if ablation:
        if verbose:
            print("  [2/4] ablation: closed-loop vs open-loop button...")
        abl = ablation_button()
    if verbose:
        print("  [3/4] force trace + free-space precision...")
    trace = force_trace(); prec = precision_test()
    if verbose:
        print("  [4/4] writing evidence pack...")
    top = build_reports(rows, prec, trace, abl)
    if verbose:
        print(f"[OK] evidence pack -> {EVID}")
        print(json.dumps({k: v for k, v in top.items() if k not in ("artifacts",)}, indent=2))
    return top


if __name__ == "__main__":
    run()
